/** Five-star distribution that matches the average, for the rating bars. */
export function ratingBreakdown(p: Place): number[] {
  const r = p.rating;
  const five = Math.round(Math.min(92, Math.max(40, (r - 3.6) * 70)));
  const four = Math.round(Math.max(6, (100 - five) * 0.62));
  const three = Math.round(Math.max(2, (100 - five - four) * 0.6));
  const two = Math.max(1, Math.round((100 - five - four - three) * 0.55));
  const one = Math.max(0, 100 - five - four - three - two);
  return [five, four, three, two, one];
}

export const formatCount = (n: number) => n.toLocaleString('en-US');
